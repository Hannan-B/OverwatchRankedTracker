const TIME_STATS = new Set<string>([
  "OBJ CONTEST TIME",
])

export function statFormat(canonicalName: string): StatFormat {
  const n = canonicalName.toUpperCase().trim()
  if (TIME_STATS.has(n)) return 'time'
  if (PERCENT_STATS.has(n)) return 'percent'
  return 'number'
}

// normalise any raw stat name to its canonical form (for display/lookup)
export function normaliseStat(raw: string): string {
  const n = raw.toUpperCase().trim()
  return STAT_NORMALISE[n] || n
}

// format a numeric value for display given the stat's type
export function formatStatValue(canonicalName: string, value: number | null): string {
  if (value == null) return '—'
  const fmt = statFormat(canonicalName)
  if (fmt === 'percent') return `${Math.round(value * 10) / 10}%`
  if (fmt === 'time') {
    const total = Math.round(value)
    const m = Math.floor(total / 60)
    const s = total % 60
    return `${m}:${s.toString().padStart(2, '0')}`
  }
  return `${Math.round(value * 100) / 100}`
}

